#!/usr/bin/env python3
"""Build the MIT campus dataset used by the SEITR simulation.

Joins the campus files in seitr-sim/data (buildings, estimated walking distance
matrix, sample student sizes) and writes:

  seitr-sim/mit-campus.js   window.MIT_CAMPUS, the dataset the page loads by default
  seitr-sim/mit-campus.csv  the same data in the page's CSV import format

Run:  python3 seitr-sim/tools/build_mit_dataset.py
"""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"


def read_csv(path):
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def main():
    buildings_rows = read_csv(DATA / "campus_buildings.csv")
    sizes = {r["id"]: r for r in read_csv(DATA / "sample_student_sizes.csv")}
    walk_m = {r["id"]: r for r in read_csv(DATA / "distance_matrix_walk_m.csv")}
    walk_min = {r["id"]: r for r in read_csv(DATA / "distance_matrix_walk_min.csv")}

    ids = [r["id"] for r in buildings_rows]
    missing = [i for i in ids if i not in sizes or i not in walk_m]
    if missing:
        raise SystemExit(f"missing student size or distance rows for: {', '.join(missing)}")

    buildings = []
    for row in buildings_rows:
        bid = row["id"]
        buildings.append({
            "id": bid,
            "name": row["name"],
            "type": row["primary_type"],
            "population": int(sizes[bid]["population"]),
            "zone": row["zone"],
            "mitNumber": row["mit_number"],
            "hosts": [h for h in row["hosts"].split(";") if h],
            "about": row["what_it_does"],
            "populationBasis": sizes[bid]["basis"],
        })

    distances = [[round(float(walk_m[a][b])) for b in ids] for a in ids]
    minutes = [[float(walk_min[a][b]) for b in ids] for a in ids]

    dataset = {
        "campus": "MIT",
        "source": "seitr-sim/data (see campus_overview.md) — distances are haversine ×1.25 at 80 m/min, not routed",
        "buildings": buildings,
        "distances": distances,
        "walkMinutes": minutes,
    }

    js = ROOT / "mit-campus.js"
    js.write_text(
        "// Generated by tools/build_mit_dataset.py from seitr-sim/data — do not edit by hand.\n"
        "window.MIT_CAMPUS = " + json.dumps(dataset, indent=1, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )

    names = [b["name"] for b in buildings]
    with (ROOT / "mit-campus.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["name", "type", "population"] + names)
        for i, b in enumerate(buildings):
            w.writerow([b["name"], b["type"], b["population"]] + distances[i])

    print(f"wrote {js.name} and mit-campus.csv: {len(buildings)} buildings, "
          f"{sum(b['population'] for b in buildings)} students")


if __name__ == "__main__":
    main()
